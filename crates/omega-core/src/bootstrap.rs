//! Bootstrap pipeline — Vision → PRD → Plan template generation.

use serde::{Deserialize, Serialize};
use std::path::Path;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum BootstrapPhase {
    Vision,
    Prd,
    Brand,
    Plan,
    Execute,
}

impl BootstrapPhase {
    pub fn all() -> &'static [BootstrapPhase] {
        &[
            BootstrapPhase::Vision,
            BootstrapPhase::Prd,
            BootstrapPhase::Brand,
            BootstrapPhase::Plan,
            BootstrapPhase::Execute,
        ]
    }

    pub fn label(&self) -> &'static str {
        match self {
            BootstrapPhase::Vision => "Vision",
            BootstrapPhase::Prd => "PRD",
            BootstrapPhase::Brand => "Brand",
            BootstrapPhase::Plan => "Plan",
            BootstrapPhase::Execute => "Execute",
        }
    }

    pub fn icon(&self) -> &'static str {
        match self {
            BootstrapPhase::Vision => "🔭",
            BootstrapPhase::Prd => "📋",
            BootstrapPhase::Brand => "🎨",
            BootstrapPhase::Plan => "📐",
            BootstrapPhase::Execute => "🔨",
        }
    }
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct BootstrapState {
    pub project_name: String,
    pub current_phase: BootstrapPhase,
    pub completed: Vec<BootstrapPhase>,
    pub started_at: String,
}

impl BootstrapState {
    pub fn new(project_name: &str) -> Self {
        Self {
            project_name: project_name.to_string(),
            current_phase: BootstrapPhase::Vision,
            completed: Vec::new(),
            started_at: chrono::Utc::now().to_rfc3339(),
        }
    }

    pub fn mark_done(&mut self, phase: BootstrapPhase) {
        if !self.completed.contains(&phase) {
            self.completed.push(phase);
        }
        // advance to next phase
        let all = BootstrapPhase::all();
        if let Some(pos) = all.iter().position(|p| *p == phase) {
            if pos + 1 < all.len() {
                self.current_phase = all[pos + 1];
            }
        }
    }

    pub fn is_done(&self, phase: BootstrapPhase) -> bool {
        self.completed.contains(&phase)
    }

    pub fn progress_pct(&self) -> f32 {
        let total = BootstrapPhase::all().len() as f32;
        self.completed.len() as f32 / total * 100.0
    }

    pub fn state_path(project_dir: &Path) -> std::path::PathBuf {
        project_dir.join(".omega").join("bootstrap.json")
    }

    pub fn load(project_dir: &Path) -> Option<Self> {
        let path = Self::state_path(project_dir);
        std::fs::read_to_string(path)
            .ok()
            .and_then(|s| serde_json::from_str(&s).ok())
    }

    pub fn save(&self, project_dir: &Path) -> anyhow::Result<()> {
        let path = Self::state_path(project_dir);
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent)?;
        }
        let json = serde_json::to_string_pretty(self)?;
        std::fs::write(path, json)?;
        Ok(())
    }
}

