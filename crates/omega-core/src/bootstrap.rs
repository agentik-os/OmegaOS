pub fn generate_feature_spec(
    feature_id: &str,
    feature_name: &str,
    project_dir: &Path,
) -> anyhow::Result<()> {
    let content = format!(
        r#"# {id}: {name}

## User Story

As a [persona], I want to [action] so that [benefit].

## Acceptance Criteria

- [ ]
- [ ]
- [ ]

## Technical Design

### Components
-

### Data Flow
-

### API Endpoints
-

## Edge Cases

1.
2.

## Dependencies

- Depends on: [other feature IDs]
- Blocks: [other feature IDs]

## Test Plan

- [ ] Unit tests for [component]
- [ ] Integration test for [flow]
- [ ] E2E test for [user journey]
"#,
        id = feature_id,
        name = feature_name,
    );

    let dir = project_dir.join("docs").join("FEATURES");
    std::fs::create_dir_all(&dir)?;
    let filename = format!("{}-{}.md", feature_id, slug(feature_name));
    std::fs::write(dir.join(filename), content)?;
    Ok(())
}

fn slug(s: &str) -> String {
    s.to_lowercase()
        .chars()
        .map(|c| if c.is_alphanumeric() { c } else { '-' })
        .collect::<String>()
        .trim_matches('-')
        .to_string()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn bootstrap_state_progression() {
        let mut state = BootstrapState::new("TestApp");
        assert_eq!(state.current_phase, BootstrapPhase::Vision);
        assert!(!state.is_done(BootstrapPhase::Vision));

        state.mark_done(BootstrapPhase::Vision);
        assert!(state.is_done(BootstrapPhase::Vision));
        assert_eq!(state.current_phase, BootstrapPhase::Prd);

        state.mark_done(BootstrapPhase::Prd);
        assert_eq!(state.current_phase, BootstrapPhase::Brand);
        assert!((state.progress_pct() - 40.0).abs() < 0.1);
    }

    #[test]
    fn template_generation() {
        let tmp = std::env::temp_dir().join("omega-bootstrap-test");
        let _ = std::fs::remove_dir_all(&tmp);
        std::fs::create_dir_all(&tmp).unwrap();

        generate_vision_template("TestApp", &tmp).unwrap();
        assert!(tmp.join("docs/VISION.md").exists());

        generate_prd_template("TestApp", &tmp).unwrap();
        assert!(tmp.join("docs/PRD.md").exists());

        generate_feature_spec("F-001", "User Auth", &tmp).unwrap();
        assert!(tmp.join("docs/FEATURES/F-001-user-auth.md").exists());

        let _ = std::fs::remove_dir_all(&tmp);
    }
}
